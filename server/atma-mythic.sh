#!/usr/bin/env bash
# Project ATMA — Mythic server launcher (lab-only, localhost-first)
#
# This script does NOT run a Mythic server on GitHub Pages and does NOT
# build payloads or target any host. It automates the official, public
# Mythic installation on YOUR OWN Linux host, for YOUR OWN lab:
#   1. clone its-a-feature/Mythic
#   2. build mythic-cli (root `make` pulls the official builder image
#      ghcr.io/its-a-feature/mythic_cli and copies the binary out;
#      `make local` in Mythic_CLI needs a local Go toolchain instead)
#   3. sudo ./mythic-cli start  (Docker containers: mythic server,
#      Postgres, RabbitMQ, React UI, plus any installed agents/C2)
#   4. optionally install a small lab set of agents + the http C2 profile
#
# Run it ON the Linux host that will run Mythic, not on a phone and not
# in this Muse sandbox (which has no Docker or Go, and is ephemeral).
#
#   bash server/atma-mythic.sh check
#   bash server/atma-mythic.sh build
#   bash server/atma-mythic.sh start
#   bash server/atma-mythic.sh install-lab
#   bash server/atma-mythic.sh status
#   bash server/atma-mythic.sh stop
#
# Safety defaults:
#   - Mythic binds to localhost only unless you explicitly set
#     ATMA_ALLOW_REMOTE=1 AND pass --remote. Even then this script does
#     NOT open firewall ports for you.
#   - No credentials are written into this repo. The mythic_admin
#     password lives only in <mythic-dir>/.env, generated by Mythic on
#     first start. This script prints where to find it; it never
#     commits, uploads, or sends it anywhere.
#   - Use only against systems you own or are explicitly authorised
#     to test. A C2 server pointed at anything else is out of scope.
set -euo pipefail

MYTHIC_DIR="${ATMA_MYTHIC_DIR:-$HOME/mythic-server/Mythic}"
MYTHIC_URL="${ATMA_MYTHIC_URL:-https://127.0.0.1:7443}"
AGENTS="${ATMA_AGENTS:-Apollo Poseidon Medusa Apfell}"
C2_PROFILES="${ATMA_C2:-http}"

die() { echo "ATMA: $*" >&2; exit 1; }
need() { command -v "$1" >/dev/null 2>&1 || die "missing required tool: $1"; }

cmd_check() {
  echo "ATMA Mythic launcher — doctor check"
  echo "  host dir:   $MYTHIC_DIR"
  echo "  mythic url: $MYTHIC_URL"
  for t in git curl sudo; do
    if command -v "$t" >/dev/null 2>&1; then echo "  ok: $t"; else echo "  MISSING: $t"; fi
  done
  if command -v docker >/dev/null 2>&1; then
    echo "  ok: docker $(docker --version 2>/dev/null || true)"
    docker compose version >/dev/null 2>&1 && echo "  ok: docker compose plugin" || echo "  MISSING: docker compose plugin (needed by mythic-cli)"
  else
    echo "  MISSING: docker — Mythic's official path needs it."
    echo "    Mythic ships install scripts in its repo root, e.g."
    echo "    install_docker_ubuntu.sh / install_docker_debian.sh / install_docker_kali.sh"
    echo "    (review one for your distro first — it needs sudo)"
  fi
  if command -v go >/dev/null 2>&1; then echo "  ok: go (only needed for 'make local')"; else echo "  note: go not found — the default 'make' path uses a Docker builder image instead"; fi
  echo "  This sandbox (Muse VM / Android) is NOT a valid host: it has no"
  echo "  Docker/Go and it disappears. Run this script on your Linux host."
}

cmd_clone() {
  need git
  if [ -d "$MYTHIC_DIR/.git" ]; then
    echo "ATMA: Mythic checkout already exists at $MYTHIC_DIR — pulling latest"
    git -C "$MYTHIC_DIR" pull --ff-only || echo "ATMA: pull failed; keeping existing checkout"
  else
    echo "ATMA: cloning its-a-feature/Mythic to $MYTHIC_DIR"
    mkdir -p "$(dirname "$MYTHIC_DIR")"
    git clone https://github.com/its-a-feature/Mythic "$MYTHIC_DIR"
  fi
}

cmd_build() {
  cmd_clone
  need docker
  echo "ATMA: building mythic-cli (root 'make' — Docker builder image)"
  (cd "$MYTHIC_DIR" && sudo make)
  ls -l "$MYTHIC_DIR/mythic-cli"
  echo "ATMA: mythic-cli ready. Next: bash server/atma-mythic.sh start"
}

cmd_start() {
  [ -x "$MYTHIC_DIR/mythic-cli" ] || die "mythic-cli not built yet — run: bash server/atma-mythic.sh build"
  if [ "${ATMA_ALLOW_REMOTE:-0}" = "1" ] && [ "${1:-}" = "--remote" ]; then
    echo "ATMA: WARNING — remote bind requested. You asked for this explicitly."
    echo "ATMA: this script does not open firewall ports. Bind settings are"
    echo "ATMA: yours to set via './mythic-cli config set' (see server/README.md)."
  else
    echo "ATMA: localhost-first start (default). Remote access, if you ever want"
    echo "ATMA: it, should go through SSH forwarding or Tailscale, not a public port."
  fi
  echo "ATMA: starting Mythic (first start pulls/builds containers — several minutes)"
  (cd "$MYTHIC_DIR" && sudo ./mythic-cli start)
  echo "ATMA: waiting for the UI at $MYTHIC_URL (self-signed cert — expect a browser warning)"
  for _ in $(seq 1 60); do
    if curl -ks -o /dev/null -w "%{http_code}" "$MYTHIC_URL" 2>/dev/null | grep -qE '^(200|302|401|403)$'; then
      echo "ATMA: Mythic UI is responding at $MYTHIC_URL"
      break
    fi
    sleep 10
  done
  echo "ATMA: admin user is 'mythic_admin'. Its generated password is in:"
  echo "ATMA:   $MYTHIC_DIR/.env"
  echo "ATMA: ATMA console (Pages): https://etienne0101-lab.github.io/Project-ATMA/"
  echo "ATMA: From the SAME machine, open the console and use Connect with"
  echo "ATMA:   $MYTHIC_URL  — from a phone, first SSH-forward 7443 or use"
  echo "ATMA:   Tailscale, because Pages (https) cannot reach your host's"
  echo "ATMA:   localhost and will block plain-http / self-signed cross-origin calls."
}

cmd_install_lab() {
  [ -x "$MYTHIC_DIR/mythic-cli" ] || die "mythic-cli not built yet — run: bash server/atma-mythic.sh build"
  echo "ATMA: installing lab agents: $AGENTS"
  for a in $AGENTS; do
    (cd "$MYTHIC_DIR" && sudo ./mythic-cli install github "https://github.com/MythicAgents/$a") || echo "ATMA: install failed for $a — check the repo name / network and retry"
  done
  echo "ATMA: installing C2 profiles: $C2_PROFILES"
  for c in $C2_PROFILES; do
    (cd "$MYTHIC_DIR" && sudo ./mythic-cli install github "https://github.com/MythicC2Profiles/$c") || echo "ATMA: install failed for $c"
  done
  echo "ATMA: installed set done. Restart Mythic to pick up new services:"
  echo "ATMA:   cd $MYTHIC_DIR && sudo ./mythic-cli restart"
}

cmd_status() {
  [ -x "$MYTHIC_DIR/mythic-cli" ] || die "mythic-cli not built yet"
  (cd "$MYTHIC_DIR" && sudo ./mythic-cli status)
}

cmd_stop() {
  [ -x "$MYTHIC_DIR/mythic-cli" ] || die "mythic-cli not built yet"
  (cd "$MYTHIC_DIR" && sudo ./mythic-cli stop)
  echo "ATMA: Mythic stopped. ATMA console falls back to demo mode."
}

cmd_logs() {
  [ -x "$MYTHIC_DIR/mythic-cli" ] || die "mythic-cli not built yet"
  (cd "$MYTHIC_DIR" && sudo ./mythic-cli logs "${1:-mythic_server}")
}

case "${1:-help}" in
  check) cmd_check ;;
  build) cmd_build ;;
  start) cmd_start "${2:-}" ;;
  install-lab) cmd_install_lab ;;
  status) cmd_status ;;
  stop) cmd_stop ;;
  logs) cmd_logs "${2:-mythic_server}" ;;
  *) echo "Usage: $0 {check|build|start|install-lab|status|stop|logs [container]}"; exit 1 ;;
esac
